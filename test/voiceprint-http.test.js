import test from 'node:test';
import assert from 'node:assert/strict';
import {EventEmitter} from 'node:events';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {start} from '../src/main.js';
test('voiceprint HTTP requires CSRF, consent and idle audio, encrypts a profile, and blocks native bypass',async t=>{
  const workspace=await mkdtemp(path.join(tmpdir(),'zhiwei-owner-http-')),rpc=new EventEmitter();Object.assign(rpc,{connected:true,stop:async()=>{},request:async()=>{throw Error('offline');}});
  const app=await start({port:0,workspace,dataDir:path.join(workspace,'data'),rpc});t.after(async()=>{await app.close();await rm(workspace,{recursive:true,force:true});});await app.ready;
  const state=await(await fetch(app.origin+'/api/state')).json(),headers={Origin:app.origin,'X-Zhiwei-CSRF':state.csrf,'Content-Type':'application/json'};
  assert.equal(state.voice.voiceprint.enabled,false);assert.equal(state.voice.voiceprint.enrolled,false);
  const post=(route,body,custom=headers)=>fetch(app.origin+'/api/'+route,{method:'POST',headers:custom,body:JSON.stringify(body)});
  assert.equal((await post('voiceprint',{action:'delete'},{...headers,'X-Zhiwei-CSRF':'wrong'})).status,403);
  assert.equal((await post('voiceprint',{action:'enroll',consent:false,samples:[]})).status,400);
  assert.equal((await post('memory/remember',{text:'中文回答'},{...headers,'X-Zhiwei-CSRF':'wrong'})).status,403);
  assert.equal((await post('memory/remember',{text:''})).status,400);
  assert.equal((await post('memory/remember',{text:'中文回答'})).status,200);
  assert.equal(app.client.memory.search('中文回答').length,1);
  const v=app.client.voice.config.voiceprint;v.embedder=async()=>[1,0,0];const pcm=Buffer.alloc(384000);for(let i=0;i<pcm.length;i+=2)pcm.writeInt16LE(i%4?4000:-4000,i);
  const body={action:'enroll',consent:true,samples:Array(3).fill(pcm.toString('base64'))};
  const enrolled=await post('voiceprint',body);assert.equal(enrolled.status,200,await enrolled.clone().text());assert.equal((await enrolled.json()).sampleCount,3);
  assert.equal((await post('voiceprint',{action:'configure',enabled:true,threshold:.6})).status,400);
  for(let i=0;i<3;i++)assert.equal((await post('voiceprint',body)).status,200);
  assert.equal((await post('voiceprint',{action:'configure',enabled:true,threshold:.6})).status,200);
  const native=await post('realtime/start',{sdp:'invalid'});assert.equal(native.status,400);assert.match((await native.json()).error,/声纹/);
  app.client.voice.enabled=true;assert.equal((await post('voiceprint',{action:'delete'})).status,400);app.client.voice.enabled=false;
  assert.equal((await post('voiceprint',{action:'delete'})).status,200);assert.equal(v.profile,null);
  for(const module of ['voiceprint-view.js'])assert.equal((await fetch(app.origin+'/'+module)).status,200);
});
